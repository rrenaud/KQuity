#!/usr/bin/env python3
"""Generate golden test vectors for the HLS testbench.

Loads a held-out slice of Phase-1 events, quantizes to int8 using the
canonical pipeline in `kquity_pressure_ref.py`, computes the bit-exact
int16 logit and uint16 probability, then emits `golden_kquity_pressure.h`
with arrays the C++ testbench can compare against.

Includes endpoint clamp probes (max/min of each input).
"""
from __future__ import annotations

import argparse
import glob
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
HLS_DIR = HERE
REPO = HERE.parents[2]
sys.path.insert(0, str(REPO))
sys.path.insert(0, str(HLS_DIR))

import fast_materialize as fm  # noqa: E402
import kquity_pressure_ref as ref  # noqa: E402


def diffs(X):
    egg = X[:, 0] - X[:, 20]
    food = X[:, 1] - X[:, 21]
    snail = X[:, 49]
    sol = X[:, 3] - X[:, 23]
    war = X[:, 2] - X[:, 22]
    ber = X[:, 51]
    return np.column_stack([egg, food, snail, sol, war, ber]).astype(np.float64)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--phase4-json",
        default=str(HERE.parents[0] / "results/phase4_fixed_point.json"),
    )
    ap.add_argument("--csv-glob", default=str(REPO / "tests/benchmark_events_*.csv.gz"))
    ap.add_argument(
        "--n",
        type=int,
        default=128,
        help="random sample of test-pool events for the testbench",
    )
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out", default=str(HLS_DIR / "golden_kquity_pressure.h"))
    args = ap.parse_args()

    # Reload Phase 4 weights / bias
    j = json.loads(Path(args.phase4_json).read_text())
    consts = ref.make_constants(j["float_weights"], j["float_intercept"])

    # Build sampling pool from CSV shards (first shard is enough)
    paths = sorted(glob.glob(args.csv_glob))
    if not paths:
        raise FileNotFoundError(args.csv_glob)
    res = fm.fast_materialize(paths[0], drop_state_probability=0.0)
    X = res[0]
    D = diffs(X)
    rng = np.random.RandomState(args.seed)
    idx = rng.choice(len(D), size=min(args.n, len(D)), replace=False)
    D_sample = D[idx]

    # Endpoint clamp probes (deterministic, append to the random sample)
    edge_rows = []
    for nm in ref.DIFF_NAMES:
        norm = ref.FEATURE_NORM[nm]
        for v in (
            norm["center"] - norm["half_range"],
            norm["center"] + norm["half_range"],
            norm["center"] + 1e9,  # over-cap -> clamp positive
            norm["center"] - 1e9,  # over-cap -> clamp negative
        ):
            row = np.array([norm["center"]] * len(ref.DIFF_NAMES), dtype=np.float64)
            # set this feature to the probe value; others at center
            row_filled = []
            for nm2 in ref.DIFF_NAMES:
                if nm2 == nm:
                    row_filled.append(v)
                else:
                    row_filled.append(ref.FEATURE_NORM[nm2]["center"])
            edge_rows.append(np.array(row_filled, dtype=np.float64))
    edge_rows = np.array(edge_rows)

    D_all = np.concatenate([D_sample, edge_rows])
    n = D_all.shape[0]

    # Quantize + apply pure-int primitive
    x_int = ref.quantize_features_int8(D_all)
    acc = ref.kquity_logit_q8(x_int, consts["w_int"], consts["b_acc"])
    logit_q4_12 = ref.saturate_int16(acc)
    lut = ref.build_sigmoid_lut()
    prob_uq16 = ref.kquity_prob_lut(logit_q4_12, lut)

    # Emit header
    lines = []
    lines.append("// SPDX-License-Identifier: MIT")
    lines.append("// Generated by experiments/kquity_hw/hls/gen_golden.py")
    lines.append("// Random eval slice plus endpoint clamp probes.")
    lines.append("// Do not edit by hand.")
    lines.append("#ifndef KQUITY_GOLDEN_H")
    lines.append("#define KQUITY_GOLDEN_H")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append(f"#define KQUITY_GOLDEN_N {n}")
    lines.append("")

    def fmt_int8_row(r):
        return ", ".join(f"{int(v):>4d}" for v in r)

    lines.append("// 6-column int8 inputs (Q1.7): egg, food, snail, sol, war, ber.")
    lines.append(f"static const int8_t kquity_golden_x[KQUITY_GOLDEN_N][6] = {{")
    for i in range(n):
        comma = "," if i < n - 1 else ""
        lines.append("    { " + fmt_int8_row(x_int[i]) + " }" + comma)
    lines.append("};")
    lines.append("")
    lines.append("// Expected int16 Q4.12 logits.")
    lines.append(
        f"static const int16_t kquity_golden_logit_q4_12[KQUITY_GOLDEN_N] = {{"
    )
    for i in range(0, n, 8):
        row = logit_q4_12[i : i + 8]
        s = ", ".join(f"{int(v):>6d}" for v in row)
        comma = "," if i + 8 < n else ""
        lines.append(f"    {s}{comma}")
    lines.append("};")
    lines.append("")
    lines.append("// Expected uint16 probabilities (sigmoid LUT).")
    lines.append(f"static const uint16_t kquity_golden_prob[KQUITY_GOLDEN_N] = {{")
    for i in range(0, n, 8):
        row = prob_uq16[i : i + 8]
        s = ", ".join(f"{int(v):>5d}" for v in row)
        comma = "," if i + 8 < n else ""
        lines.append(f"    {s}{comma}")
    lines.append("};")
    lines.append("")
    lines.append("#endif  // KQUITY_GOLDEN_H")
    Path(args.out).write_text("\n".join(lines) + "\n")
    print(
        f"wrote {args.out}  (N={n}: {len(idx)} random + {len(edge_rows)} edge probes)"
    )


if __name__ == "__main__":
    main()
